"""CALVIN runner (Mees et al., 2022) - long-horizon multi-task language-conditioned
(LH-MTLC) protocol, ABC->D split (evaluation always takes place in scene D).

Official protocol (``calvin_agent/evaluation/evaluate_policy.py``):

* ``get_sequences(1000)`` - 1000 chains of 5 sub-tasks with their initial
  conditions, generated by the vendored official code
  (:mod:`vlaquantbench.benchmarks._calvin_official`, no ``pyhash`` needed);
* per chain: ``env.reset(robot_obs, scene_obs)`` from
  ``get_env_state_for_initial_condition`` (fixed neutral arm pose, block
  layout/rotation derived deterministically from the condition); the five
  sub-tasks are rolled out **in order, stopping at the first failure**, the
  robot is *not* reset between sub-tasks;
* per sub-task: language = first annotation of
  ``conf/annotations/new_playtable_validation.yaml``; at most ``EP_LEN = 360``
  control steps (30 Hz); success as soon as the task oracle
  (``calvin_env.envs.tasks.Tasks`` with ``new_playtable_tasks.yaml``) reports
  the sub-task between ``start_info`` and the current ``env.get_info()``;
* metric: number of consecutive successes (0-5); the benchmark score is the
  average over the 1000 chains (``Avg. Len.``); ``success`` in our records
  means all five sub-tasks were solved.

Environment: ``calvin_env`` ``PlayTableSimEnv`` instantiated from the
validation split's ``.hydra/merged_config.yaml`` (a copy for ABC->D ships in
``configs/calvin/ABC_D``; the tactile camera is dropped unless ``tacto`` is
importable). Observations: ``rgb_static`` 200x200, ``rgb_gripper`` 84x84,
``robot_obs`` (15) and ``scene_obs`` (24). Actions: a 7-vector is interpreted
as *relative* EE motion, a ``(xyz, quat_xyzw, gripper)`` tuple as an absolute
target pose; the gripper must be exactly -1 (close) or +1 (open).

The official ``rollout`` calls ``model.reset()`` at every sub-task; the X-VLA
client keeps its state across a chain. The runner calls ``adapter.reset(task)``
once per chain and ``adapter.reset_subtask(task, i)`` (if defined) at every
sub-task. Adapters may declare ``calvin_ep_len`` (X-VLA: 720); the value used
is recorded per episode.

Requires: ``calvin_env`` (PyBullet) + ``hydra``/``omegaconf``; ``EGL`` for
headless rendering (``use_egl: true`` in the config).
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Any, ClassVar

import numpy as np

from ..models.base import TaskSpec, VLAAdapter
from ..profiling import LatencyMeter
from .base import BenchmarkRunner, EpisodeOutcome

__all__ = ["CalvinRunner", "EP_LEN", "NUM_SEQUENCES"]

log = logging.getLogger(__name__)

EP_LEN = 360
NUM_SEQUENCES = 1000
CONFIG_DIR = Path(__file__).resolve().parents[2] / "configs" / "calvin"


class CalvinRunner(BenchmarkRunner):
    name: ClassVar[str] = "calvin"
    primary_metric: ClassVar[str] = "avg_len"

    def __init__(self, suite: str = "ABC_D", *, dataset_dir: str | None = None, ep_len: int | None = None,
                 num_sequences: int = NUM_SEQUENCES, **kwargs: Any):
        if suite not in self.suites():
            raise ValueError(f"unknown CALVIN suite {suite!r}; expected one of {self.suites()}")
        super().__init__(suite, **kwargs)
        self.dataset_dir = dataset_dir or os.environ.get("CALVIN_DATASET_DIR") or str(CONFIG_DIR / suite)
        self.ep_len = ep_len
        self.num_sequences = num_sequences
        self._env = None
        self._oracle = None
        self._annotations: dict[str, list[str]] | None = None
        self._sequences: list | None = None

    @classmethod
    def suites(cls) -> tuple[str, ...]:
        return ("ABC_D", "ABCD_D", "D_D")  # same scene-D environment; only the checkpoint differs

    @classmethod
    def default_episodes_per_task(cls) -> int:
        return 1  # one "task" = one chain

    def configure_for(self, adapter: VLAAdapter) -> None:
        if self.ep_len is None and self.max_steps_override is None:
            self.ep_len = int(getattr(adapter, "calvin_ep_len", EP_LEN) or EP_LEN)

    def run(self, adapter: VLAAdapter, writer=None, **kwargs):  # type: ignore[override]
        self.configure_for(adapter)
        return super().run(adapter, writer, **kwargs)

    # ------------------------------------------------------------------ #
    def sequences(self) -> list:
        if self._sequences is None:
            from ._calvin_official import get_sequences

            self._sequences = get_sequences(self.num_sequences)
        return self._sequences

    def annotations(self) -> dict[str, list[str]]:
        if self._annotations is None:
            from omegaconf import OmegaConf  # type: ignore

            self._annotations = OmegaConf.to_container(OmegaConf.load(CONFIG_DIR / "new_playtable_validation.yaml"))  # type: ignore
        return self._annotations

    def tasks(self) -> list[TaskSpec]:
        ep_len = self.max_steps(self.ep_len or EP_LEN)
        specs = []
        for i, (initial_state, seq) in enumerate(self.sequences()):
            specs.append(
                TaskSpec(
                    benchmark=self.name,
                    suite=self.suite,
                    task_id=i,
                    task_name=" -> ".join(seq),
                    instruction=self.annotations()[seq[0]][0],
                    max_steps=ep_len,  # per sub-task
                    extra={"initial_state": dict(initial_state), "subtasks": list(seq)},
                )
            )
        return specs

    def _make_env(self):
        if self._env is not None:
            return self._env
        import calvin_env  # type: ignore
        import hydra  # type: ignore
        from omegaconf import OmegaConf  # type: ignore

        if getattr(calvin_env, "__file__", None) is None and getattr(calvin_env, "__path__", None):
            # calvin_env installed as a namespace package: PlayTableSimEnv.__init__ ends with
            # get_git_commit_hash(Path(calvin_env.__file__)) and would raise on None.
            calvin_env.__file__ = str(Path(list(calvin_env.__path__)[0]) / "__init__.py")

        cfg_path = Path(self.dataset_dir) / "validation" / ".hydra" / "merged_config.yaml"
        if not cfg_path.exists():
            raise FileNotFoundError(f"{cfg_path} not found; pass --bench-kwargs dataset_dir=/path/to/calvin/task_ABC_D")
        conf = OmegaConf.load(cfg_path)
        try:
            import tacto  # noqa: F401  # type: ignore
        except Exception:
            if "tactile" in conf.cameras:
                del conf.cameras["tactile"]
        if not hydra.core.global_hydra.GlobalHydra.instance().is_initialized():
            hydra.initialize(".")
        self._env = hydra.utils.instantiate(conf.env, show_gui=False, use_vr=False, use_scene_info=True)
        self._oracle = hydra.utils.instantiate(OmegaConf.load(CONFIG_DIR / "new_playtable_tasks.yaml"))
        return self._env

    # ------------------------------------------------------------------ #
    def run_episode(self, adapter: VLAAdapter, task: TaskSpec, episode: int, meter: LatencyMeter) -> EpisodeOutcome:
        from ._calvin_official import get_env_state_for_initial_condition

        env = self._make_env()
        robot_obs, scene_obs = get_env_state_for_initial_condition(task.extra["initial_state"])
        env.reset(robot_obs=robot_obs, scene_obs=scene_obs)
        adapter.reset(task)

        completed = 0
        total_steps = 0
        for k, subtask in enumerate(task.extra["subtasks"]):
            instruction = self.annotations()[subtask][0]
            if hasattr(adapter, "reset_subtask"):
                adapter.reset_subtask(task, k)
            obs = env.get_obs()
            start_info = env.get_info()
            success = False
            for step in range(task.max_steps):
                images = {"rgb_static": obs["rgb_obs"]["rgb_static"], "rgb_gripper": obs["rgb_obs"]["rgb_gripper"]}
                raw = {"robot_obs": np.asarray(obs["robot_obs"]), "scene_obs": np.asarray(obs["scene_obs"]), "subtask": subtask, "subtask_index": k}
                observation = self.make_obs(images, instruction, np.asarray(obs["robot_obs"]), step, raw)
                with meter.measure():
                    action = adapter.act(observation, task)
                action = self._format_action(action)
                obs, _, _, info = env.step(action)
                total_steps += 1
                if len(self._oracle.get_task_info_for_set(start_info, info, {subtask})) > 0:
                    success = True
                    break
            if not success:
                break
            completed += 1
        return EpisodeOutcome(
            success=(completed == len(task.extra["subtasks"])),
            steps=total_steps,
            subtasks_completed=completed,
            extra={"ep_len": task.max_steps, "subtasks": task.extra["subtasks"]},
        )

    @staticmethod
    def _format_action(action):
        if isinstance(action, tuple):
            pos, rot, grip = action
            return (np.asarray(pos, dtype=np.float64), np.asarray(rot, dtype=np.float64), int(np.sign(grip) or 1))
        a = np.asarray(action, dtype=np.float64).reshape(-1)
        a[-1] = 1.0 if a[-1] > 0 else -1.0
        return a

    def close(self) -> None:
        if self._env is not None:
            try:
                self._env.close()
            except Exception:  # pragma: no cover
                pass
            self._env = None
